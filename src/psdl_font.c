const PSDL_Font PSDL_Font5x7 = {
	.width   = 5,
	.height  = 7,
	/* 6, not 5: the extra column is the gap between characters, which is why
	 * PSDL_FontWidth subtracts one at the end. */
	.advance = 6,
	.glyphs  = (const Uint16 (*)[])font5x7_glyphs,
	.stride  = 5,
};

const PSDL_Font PSDL_Font9x14 = {
	.width   = PSDL_FONT9X14_WIDTH,
	.height  = PSDL_FONT9X14_HEIGHT,
	/* The misc-fixed cell already contains its own side bearing, so the advance
	 * is the full width and PSDL_FontWidth's trailing -1 still applies. */
	.advance = PSDL_FONT9X14_ADVANCE,
	.glyphs  = (const Uint16 (*)[])font9x14_glyphs,
	.stride  = PSDL_FONT9X14_WIDTH,
};

int PSDL_FontWidth(const PSDL_Font *font, const char *text)
{
	int n = 0;
	while (text != NULL && *text++ != '\0')
		++n;
	if (font == NULL || n == 0)
		return 0;
	return n * font->advance - 1;
}

int PSDL_FontDraw(const PSDL_Font *font, SDL_Surface *dst, int x, int y,
                  Uint8 color, const char *text)
{
	if (font == NULL || dst == NULL || text == NULL)
		return x;

	/* One scratch glyph, reused for the whole string: create/free per character
	 * would push and pop the arena 40 times a line for no gain. */
	SDL_Surface *glyph = SDL_CreateRGBSurface(0, font->width, font->height, 8, 0, 0, 0, 0);
	if (glyph == NULL)
		return x;
	SDL_SetColorKey(glyph, SDL_TRUE, 0);

	const Uint16 *table = (const Uint16 *)font->glyphs;

	for (const char *p = text; *p != '\0'; ++p, x += font->advance) {
		unsigned char c = (unsigned char)*p;
		if (c < 0x20 || c > 0x7E)
			continue;

		const Uint16 *cols = table + (size_t)(c - 0x20) * font->stride;
		for (int row = 0; row < font->height; ++row) {
			Uint8 *dstrow = (Uint8 *)glyph->pixels + row * glyph->pitch;
			for (int col = 0; col < font->width; ++col)
				dstrow[col] = (cols[col] >> row) & 1 ? color : 0;
		}

		SDL_Rect at = { x, y, font->width, font->height };
		SDL_BlitSurface(glyph, NULL, dst, &at);
	}

	SDL_FreeSurface(glyph);
	return x;
}
